// Copies class-transformer's specs into test/ct/ with only mechanical edits (imports, reflect-metadata, storage clears).
// Usage: node scripts/port-ct.mjs <path-to-class-transformer-checkout>
// class-transformer is MIT licensed, Copyright (c) 2015-2020 TypeStack.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const root = process.argv[2];
if (!root) throw new Error("usage: node scripts/port-ct.mjs <class-transformer-dir>");
const dir = `${root}/test/functional`;
// Tests that depend on reflect-metadata's `design:type` (a field's declared TS type), which dto-kit does not use.
const SKIP = {
  "implicit-type-declarations.spec.ts": [
    "should run only when enabled",
    "should use implicitly defined design:type to convert value when no @Type decorator is used",
    "should use implicitly defined design:type to convert value when empty @Type() decorator is used",
    "should recognize and convert to Date",
    "should recognize and convert to string",
    "should recognize and convert to number",
    "should recognize and convert to boolean",
  ],
};

/**
 * esbuild (standard decorators) compiles `id: number;` to `this.id = void 0`, but the specs were written for TypeScript's
 * legacy output, where an undecorated, uninitialised field does not exist on the instance. Drop those declarations.
 */
function dropUndecoratedFields(src) {
  const out = [];
  let prev = "";
  for (const line of src.split("\n")) {
    const t = line.trim();
    const isField = /^(?:(?:public|private|protected|readonly) )*[A-Za-z_$][\w$]*[?!]?: [^=;]+;$/.test(t);
    if (isField && /[;{}]$/.test(prev) && !prev.startsWith("@")) continue;
    if (t && !t.startsWith("//") && !t.startsWith("*") && !t.startsWith("/*")) prev = t;
    out.push(line);
  }
  return out.join("\n");
}

/** dto-kit can't see `Map<..>`/`Set<..>` declared types, so a @Type on such a field needs `{ container }`. */
const addContainer = (src) =>
  src.replace(/@Type\((\(\) => [\w.]+)\)(\s*\n\s*(?:public )?[\w$]+\??: (Map|Set)<)/g, "@Type($1, { container: $3 })$2");

let n = 0;
for (const f of readdirSync(dir).filter((x) => x.endsWith(".spec.ts"))) {
  let s = readFileSync(`${dir}/${f}`, "utf8");
  s = s
    .split("\n")
    .filter((l) => !/^import 'reflect-metadata';/.test(l) && !/^import \{ defaultMetadataStorage \}/.test(l) && !/defaultMetadataStorage\.clear\(\)/.test(l))
    .join("\n")
    .replace(/from '\.\.\/\.\.\/src(\/[A-Za-z/]+)?'/g, "from '../../src/index.js'")
    .replace(/\bjest\./g, "vi.");
  s = addContainer(dropUndecoratedFields(s));
  for (const title of SKIP[f] ?? []) {
    s = s.replace(new RegExp("\\bit\\((['\"`])" + title.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\1", "g"), (m) => m.replace("it(", "it.skip("));
  }
  const header = `// @ts-nocheck -- generated; class-transformer's specs are loosely typed
// GENERATED by scripts/port-ct.mjs from typestack/class-transformer test/functional/${f}
// (MIT, Copyright (c) 2015-2020 TypeStack). Only imports were edited.
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
`;
  writeFileSync(`test/ct/${f.replace(".spec.ts", ".test.ts")}`, header + s);
  n++;
}
console.log("ported", n, "specs");
