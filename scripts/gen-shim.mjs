// Generates test/cv/shim.ts: maps class-validator names -> dto-kit, stubbing what dto-kit lacks.
import { readFileSync, writeFileSync } from "node:fs";
const names = JSON.parse(readFileSync("test/cv/names.json", "utf8"));
// Honest renames only (same behaviour, different name).
const alias = {
  IsUrl: "IsURL",
  IsNumberString: "IsNumericString",
  IsDateString: "IsISO8601",
  IsPhoneNumber: undefined, // not equivalent (libphonenumber) -> stays missing
};
const noop = []; // (IsDefined used to be a stand-in here; dto-kit now implements it)
let out = `// GENERATED by scripts/gen-shim.mjs
import * as dk from "../../src/index.js";

const missing: string[] = [];
/** Names of class-validator decorators applied since the last call that dto-kit does not implement. */
export const takeMissing = () => missing.splice(0).filter((v, i, a) => a.indexOf(v) === i);
const stub = (name: string) => (..._a: unknown[]) => {
  missing.push(name);
  return () => {};
};
const pick = (name: string, alias?: string) => ((dk as any)[alias ?? name] ?? stub(name)) as any;
export const constraintToString = (c: unknown) => (Array.isArray(c) ? c.join(", ") : String(c));
`;
for (const n of names) {
  if (noop.includes(n)) out += `export const ${n} = () => dk.Custom(() => undefined);\n`;
  else if (/^[a-z]/.test(n)) out += `export const ${n} = (..._a: unknown[]) => { throw new Error("function form not ported: ${n}"); };\n`;
  else out += `export const ${n} = pick(${JSON.stringify(n)}${alias[n] ? ", " + JSON.stringify(alias[n]) : ""});\n`;
}
writeFileSync("test/cv/shim.ts", out);
