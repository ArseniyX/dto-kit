// Emits test/cv/pending.test.ts: every test title from class-validator's API-level specs as it.todo().
// Usage: node scripts/todo-cv.mjs <path-to-class-validator-checkout>
import { readFileSync, writeFileSync } from "node:fs";
const root = process.argv[2];
const files = [   
  "promise-validation", "validator-options", "reject-validation", "sync-validation",
  "validation-error"]; // validation-options, custom-decorators, nested-validation, conditional/whitelist/inherited-validation are ported by hand: test/cv/*.test.ts
let out = `// GENERATED by scripts/todo-cv.mjs from typestack/class-validator (MIT, Copyright (c) 2015-2020 TypeStack).
// Titles of class-validator tests that exercise features dto-kit does not have yet (groups, async, custom
// constraints, ValidationError shape, ...). Turn each into a real test as the feature lands.
import { describe, it } from "vitest";
`;
let total = 0;
const q = String.raw`(['"\`])((?:\\.|(?!\3).)*)\3`;
for (const f of files) {
  const src = readFileSync(`${root}/test/functional/${f}.spec.ts`, "utf8").split("\n");
  out += `\ndescribe(${JSON.stringify(f)}, () => {\n`;
  const stack = []; // [indent, title]
  for (const line of src) {
    const m = line.match(new RegExp(String.raw`^(\s*)(describe|it)\(${q}`));
    if (!m) continue;
    const indent = m[1].length, kind = m[2], title = m[4];
    while (stack.length && stack[stack.length - 1][0] >= indent) { stack.pop(); out += "  ".repeat(stack.length + 1) + "});\n"; }
    if (kind === "describe") { out += "  ".repeat(stack.length + 1) + `describe(${JSON.stringify(title)}, () => {\n`; stack.push([indent, title]); }
    else { out += "  ".repeat(stack.length + 1) + `it.todo(${JSON.stringify(title)});\n`; total++; }
  }
  while (stack.length) { stack.pop(); out += "  ".repeat(stack.length + 1) + "});\n"; }
  out += "});\n";
}
writeFileSync("test/cv/pending.test.ts", out);
console.log("todo tests:", total);
