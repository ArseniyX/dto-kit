// Generates test/cv/decorators.generated.test.ts from class-validator's data-driven spec.
// Usage: node scripts/port-cv.mjs <path-to-class-validator-checkout>
// class-validator is MIT licensed, Copyright (c) 2015-2020 TypeStack. Test data is derived from it.
import { readFileSync, writeFileSync } from "node:fs";

const root = process.argv[2];
if (!root) throw new Error("usage: node scripts/port-cv.mjs <class-validator-dir>");
const src = readFileSync(`${root}/test/functional/validation-functions-and-decorators.spec.ts`, "utf8");
const lines = src.split("\n");

// 1. every name the original imports (the shim must export all of them)
const imp = src.match(/import \{([\s\S]*?)\} from '..\/..\/src\/decorator\/decorators'/)[1];
const names = [...new Set(imp.split(",").map((s) => s.trim()).filter(Boolean))];

// 2. split into top-level describe blocks
const blocks = [];
for (let i = 0; i < lines.length; i++) {
  const m = lines[i].match(/^describe\((['"`])(.+?)\1,/);
  if (!m) continue;
  let j = i + 1;
  while (j < lines.length && !/^\}\);/.test(lines[j])) j++;
  blocks.push({ name: m[2], body: lines.slice(i + 1, j) });
  i = j;
}

let out = `// @ts-nocheck -- generated; keeps class-validator's original (loosely typed) test data
// GENERATED by scripts/port-cv.mjs from typestack/class-validator (MIT, Copyright (c) 2015-2020 TypeStack).
import { describe, expect, it } from "vitest";
import ValidatorJS from "validator";
import { parse } from "../../src/index.js";
import { takeMissing, constraintToString, ${names.join(", ")} } from "./shim.js";

function check(Cls, values, expectValid) {
  const wrong = [];
  for (const v of values) {
    let ok;
    try { ok = parse(Cls, { someProperty: v }).success; } catch (e) { ok = "threw: " + e.message; }
    if (ok !== expectValid) wrong.push(v);
  }
  expect(wrong, expectValid ? "values wrongly rejected" : "values wrongly accepted").toEqual([]);
}
`;
let ported = 0, skippedShape = [];
for (const b of blocks) {
  const cut = b.body.findIndex((l) => /^\s+(it|describe)\(|\bcheck(Valid|Invalid|Returned)\w*\(|\.forEach\(/.test(l));
  const pre = (cut === -1 ? b.body : b.body.slice(0, cut)).join("\n");
  if (!/class MyClass\b/.test(pre) || !/const validValues/.test(pre) || !/const invalidValues/.test(pre)) {
    skippedShape.push(b.name);
    continue;
  }
  ported++;
  out += `
describe(${JSON.stringify(b.name)}, () => {
${pre}
  const miss = takeMissing();
  const T = miss.length ? it.skip : it;
  const tag = miss.length ? " [missing: " + miss.join(",") + "]" : "";
  T("accepts valid values" + tag, () => check(MyClass, validValues, true));
  T("rejects invalid values" + tag, () => check(MyClass, invalidValues, false));
});
`;
}
writeFileSync("test/cv/decorators.generated.test.ts", out);
writeFileSync("test/cv/names.json", JSON.stringify(names));
console.log(`blocks=${blocks.length} ported=${ported} skipped(shape)=${skippedShape.length}: ${skippedShape.join(", ")}`);
